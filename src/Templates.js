/** {{FONT}} を実際のフォント指定に展開する */
function expandTokens_(html) {
  return String(html)
    .replace(/\{\{FONT\}\}/g, FONT_STACK)
    .replace(/\{\{IMG\}\}/g, IMAGE_BASE);
}

